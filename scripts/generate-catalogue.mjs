#!/usr/bin/env node
/*
 * generate-catalogue — the catalogue as one committed JSON file, for programs.
 *
 * The same catalogue exists three times for three readers. SAMPLES.md is the
 * page for a person browsing GitHub, the overview app carries it into the
 * system, and the playground's catalogue page publishes it beside the other
 * two sample repositories. What none of them served is a program with a
 * question — "which sample shows a SmartTable, and what does my system need
 * for it?" — asked against nothing but a raw checkout or a single
 * `raw.githubusercontent.com` fetch. SAMPLES.md answers it only through a
 * regex over prose. This file is that answer: every fact the repository
 * already keeps about a sample, as data, committed.
 *
 * IT INTRODUCES NO NEW SOURCE OF TRUTH.
 * Everything here is read out of what the repository already keeps:
 *
 *   scripts/lib/scan-samples.mjs   which classes are apps, their title from
 *                                  DESCRIPT, `@summary`, `@keywords` — the
 *                                  same scan behind SAMPLES.md
 *   scripts/lib/read-packages.mjs  the packages: `.github/packages.json`
 *                                  merged with the root README's table, which
 *                                  is where "runs on" and "plays together
 *                                  with" already live
 *
 *   node scripts/generate-catalogue.mjs           write catalogue.json
 *   node scripts/generate-catalogue.mjs --check   fail if it differs
 *                                                         (this is what CI runs)
 *
 * COMMITTED, and dependency-free with it: this file exists precisely for the
 * reader who runs nothing, and staying offline is what lets it be generated
 * anywhere. The facts that would need a linter pass live beside it in
 * catalogue-derived.json (generate-derived.mjs). This file is for an
 * agent or an editor fetching one URL from `main`. A committed generated file
 * is a file that goes stale the first time somebody adds a sample and does not
 * rerun the generator — `npm run check:catalogue` is what notices, exactly as
 * `check:samples-md` does for the page. No timestamp in the output for the
 * same reason: the content is a pure function of the tree, so the check can
 * compare bytes.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { scanSamples, sampleTitle } from './lib/scan-samples.mjs';
import { packages } from './lib/read-packages.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'catalogue.json');
const CHECK = process.argv.includes('--check');

const die = (message) => {
  console.error(`generate-catalogue: ${message}`);
  process.exit(1);
};

/* -------------------------------------------------------------------- build */

const allPackages = packages(ROOT);
const byDir = new Map(allPackages.map((p) => [p.dir, p]));
const apps = scanSamples(ROOT).filter((s) => s.isApp);

const samples = apps.map((s) => {
  const pkg = byDir.get(s.pkg);
  /* Same guard as the page: an app in a subpackage would silently vanish. */
  if (!pkg) die(`${s.cls} lives in src/${s.pkg}, which is no package of .github/packages.json`);

  const { title, sub } = sampleTitle(s, s.section);
  return {
    class: s.cls.toUpperCase(),
    path: s.rel,
    package: s.pkg === '.' ? 'src' : `src/${s.pkg}`,
    technology: pkg.title,
    title: sub ? `${title} — ${sub}` : title,
    summary: s.summary,
    keywords: s.keywords ? s.keywords.split(/\s+/) : [],
    /* what this sample asks of the system — the package's facts, repeated on
     * the entry so one entry answers the whole question */
    runsOn: pkg.runsOn,
    cloud: pkg.cloud,
    needs: pkg.needs,
    branch: pkg.branch,
    setup: pkg.readme,
  };
});

const catalogue = {
  comment: 'Generated by scripts/generate-catalogue.mjs — run `npm run catalogue`. Do not edit by hand (AGENTS.md section 6).',
  repo: 'abap2UI5/samples-stack',
  role: 'Step 3 of 3 in the abap2UI5 sample family: samples (the abap2UI5 basics) -> samples-controls (the UI5 control set) -> samples-stack (abap2UI5 together with the rest of the stack). Every sample here needs something from the system beyond an abap2UI5 installation — an OData service, a RAP business object, an APC channel, a launchpad — and its entry says what.',
  start: 'Install abap2UI5, pull this repository — or the one-package branch the entry names — with abapGit, do the setup its package README asks for, then open ?app_start=<class>.',
  overviewApp: 'Z2UI5_CL_SMPS_APP_000',
  packages: allPackages.map((p) => ({
    package: p.dir === '.' ? 'src' : `src/${p.dir}`,
    technology: p.title,
    topic: p.topic,
    needs: p.needs,
    runsOn: p.runsOn,
    cloud: p.cloud,
    release: p.release,
    note: p.note,
    branch: p.branch,
    readme: p.readme,
  })),
  samples,
};

const page = `${JSON.stringify(catalogue, null, 2)}\n`;

/* The same two silent failures the page gates: an entry with nothing to search
 * for is an entry no question ever matches. check-keywords gates it too;
 * repeated here because this file is what an agent actually queries. */
const mute = samples.filter((s) => !s.summary || !s.keywords.length).map((s) => s.class);
if (mute.length) die(`${mute.join(', ')} — no @summary or no @keywords, so no question ever finds them`);
if (!samples.length) die('no apps found under src/ — the scan came back empty');

if (CHECK) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (have !== page) {
    console.error('catalogue.json is out of date — run `npm run catalogue` and commit the result.');
    console.error('It is generated from the classes and the package index; editing it by hand is how it starts lying.');
    process.exit(1);
  }
  console.log(`catalogue: up to date — ${samples.length} sample(s) in ${allPackages.length} package(s)`);
} else {
  fs.writeFileSync(OUT, page);
  console.log(`catalogue: wrote ${samples.length} sample(s) in ${allPackages.length} package(s) to ${path.relative(ROOT, OUT)}`);
}
