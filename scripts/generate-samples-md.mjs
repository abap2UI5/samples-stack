#!/usr/bin/env node
/*
 * generate-samples-md — the catalogue, as a page you can read before installing
 * anything.
 *
 * This repository had an overview APP and no overview PAGE. The app is the
 * right answer once abap2UI5, a service binding and the sample packages are on
 * a system; before that it answers nothing, and "what is actually in
 * samples-stack" was a question you could only settle by reading 39 class
 * names. abap2UI5/samples publishes SAMPLES.md for exactly that reason, so
 * this repository gets the same thing.
 *
 * THE ROW FORMAT IS NOT A STYLE CHOICE. It is byte-for-byte the shape
 * abap2UI5/samples emits, because two programs already parse those rows with a
 * regex:
 *
 *   abap2UI5/mcp-server   lib/examples.mjs   — the `examples` MCP tool
 *   abap2UI5/docs         scripts/link-samples.mjs — the Working Samples block
 *
 * Neither reads this repository yet. Emitting the same shape is what makes
 * that a configuration change over there rather than a second parser. And the
 * cost of getting it wrong is not a crash: a row that does not match is a row
 * that silently is not there — which is exactly how a format change over there
 * once took mcp-server's answer to zero without an error anywhere.
 *
 *   node scripts/generate-samples-md.mjs           write SAMPLES.md
 *   node scripts/generate-samples-md.mjs --check   fail if it differs
 *                                                          (this is what CI runs)
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { scanSamples, scanOverview, sampleTitle } from './lib/scan-samples.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'SAMPLES.md');
const CHECK = process.argv.includes('--check');

const cell = (s) => s.replace(/\|/g, '\\|').trim();

/* One row, and every part of it comes from the CLASS.
 *
 *   DESCRIPT   `Titel - Kurzbeschreibung`, split on the first ` - `. A header
 *              that only repeats its section heading is dropped — the heading
 *              already said it.
 *   @summary   the line under the title. It exists because DESCRIPT is capped
 *              at 60 characters and the useful sentence is often longer: of
 *              the 31 curated descriptions this repository already had, only
 *              13 fit in 60, and the longest is 114.
 *   @keywords  the small type — what somebody would type who does not know
 *              the sample exists.
 *
 * This used to read the overview app's catalogue instead, which was one step
 * better than DESCRIPT alone and one step short of right: it put a sample's
 * description in a different class from the sample. */
function row(s, section) {
  const { title, sub, fromSub } = sampleTitle(s, section);
  const head = sub
    ? `**${cell(title)}** — ${cell(sub)}`
    : (fromSub ? cell(title) : `**${cell(title)}**`);
  const summary = s.summary ? `<br>${cell(s.summary)}` : '';
  const keywords = s.keywords ? `<br><sub>${cell(s.keywords)}</sub>` : '';
  return `| ${head}${summary}${keywords} | [\`${s.cls.toUpperCase()}\`](${s.rel}) |`;
}

const catalogue = scanOverview(ROOT);
const all = scanSamples(ROOT);
const apps = all.filter((s) => s.isApp);
const helpers = all.filter((s) => !s.isApp);

/* One section per package, in package order. The overview app sits in src/
 * itself and is listed first — it is the way IN to everything below. */
const sections = [];
for (const s of apps) {
  const last = sections[sections.length - 1];
  if (last && last.pkg === s.pkg) last.items.push(s);
  else sections.push({ pkg: s.pkg, title: s.section || s.pkg, items: [s] });
}

const table = (items, section) => [
  '| Sample | Class |',
  '|---|---|',
  ...items.map((s) => row(s, section)),
].join('\n');

const body = sections.map((sec) => {
  const where = sec.pkg === '.' ? 'src' : `src/${sec.pkg}`;
  return `### ${sec.title} — \`${where}\`\n\n${table(sec.items, sec.title)}`;
}).join('\n\n');

/* The helpers, when the tree has any. A one-package branch can carry none
 * (build-package-branch.mjs regenerates this page there), and "0 classes are
 * not apps" over an empty table says nothing. */
const notSamples = helpers.length === 0 ? '' : `
---

## Not samples

${helpers.length} classes here are not apps and carry no tile: behavior pools,
demo data, an event consumer, the generated APC protocol class and the
language-model layer the AI samples call. They are
reached **by** a sample rather than looked up, which is why they are exempt from
the keyword rule — but a catalogue that claims to account for the tree has to be
able to say they exist.

${['| Class | What it is |', '|---|---|',
  ...helpers.map((s) => `| [\`${s.cls.toUpperCase()}\`](${s.rel}) | ${cell(s.descript)} |`)].join('\n')}
`;

const page = `<!-- Generated by scripts/generate-samples-md.mjs. Do not edit by hand:
     run \`npm run samples:md\` and commit the result (AGENTS.md section 6). -->

# The sample catalogue

Every app in this repository — ${apps.length} of them — with what it shows and a
link to its source. This is the [overview app](src/z2ui5_cl_smps_app_000.clas.abap)
as a page you can read here, before installing anything.

**What makes these different from [abap2UI5/samples](https://github.com/abap2UI5/samples):**
each one needs something from your stack — an OData service, a RAP behavior
definition, an APC channel, the Fiori Launchpad. The package README says what,
and a sample that needs nothing but abap2UI5 belongs in the other repository.

**To run one:** install [abap2UI5](https://github.com/abap2UI5/abap2UI5), pull
this repository with [abapGit](https://abapgit.org), do the setup its package
README asks for, then open \`<your endpoint>?app_start=<the class in the
right-hand column>\`. Or run \`Z2UI5_CL_SMPS_APP_000\` and click through the list
— that is the same catalogue, in the app.

**To read one:** click the class. Every sample is a single class, so the link is
the whole sample.

The small type under a title is the sample's search terms — what somebody would
type who does not know it exists. \`Ctrl+F\` on this page uses them.

---

${body}
${notSamples}`;

/* The loop the other way round. check-overview.mjs already refuses a catalogue
 * entry naming a class that does not exist; this refuses an app that exists and
 * is in no entry — the case that leaves a working sample invisible in both the
 * app and this page, which is the failure this whole file is about. The
 * overview app itself is not in its own catalogue, by definition. */
const missing = apps
  .filter((s) => s.pkg !== '.' && !catalogue.has(s.cls.toLowerCase()))
  .map((s) => s.cls);
if (missing.length) {
  console.error(`${missing.length} app(s) are in no entry of the overview catalogue:`);
  for (const m of missing) console.error(`  ${m}`);
  console.error('Add them to z2ui5_cl_smps_app_000 (AGENTS.md section 7) — an app');
  console.error('nobody lists is an app nobody finds, in the app and on this page alike.');
  process.exit(1);
}

if (CHECK) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (have !== page) {
    console.error('SAMPLES.md is out of date — run `npm run samples:md` and commit the result.');
    console.error('It is generated from the classes; editing it by hand is how it starts lying.');
    process.exit(1);
  }
  console.log(`samples-md: up to date — ${apps.length} app(s) in ${sections.length} section(s), ${helpers.length} helper(s)`);
} else {
  fs.writeFileSync(OUT, page);
  console.log(`samples-md: wrote ${apps.length} app(s) in ${sections.length} section(s), ${helpers.length} helper(s)`);
}
